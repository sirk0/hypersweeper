class Surface(NamedTuple):
    """A closed surface: its tiling {p,q}, its genus, and its group -- the
    order of the field of a PSL(2,q) (an int), or the relator a presentation
    adds to x^2, y^q and (xy)^p (a word in x, y and Y = y^-1)."""

    p: int
    q: int
    genus: int
    group: int | str


#: The surfaces, by name, in order of genus. Must match `CLOSED_SURFACES` in
#: hurwitz.ts.
CLOSED_SURFACES: dict[str, Surface] = {
    # {8,3} on genus 2: GL(2,3); its Petrie polygons are 12 long, so it needs
    # a relator of its own rather than {8,3}_12
    "bolza": Surface(8, 3, 2, "xyxyxY" * 2),
    "quartic": Surface(7, 3, 3, 7),
    # {8,3}_6: its Petrie polygons are 6 long
    "dyck": Surface(8, 3, 3, "xyxY" * 3),
    # {5,4}_6: S5
    "bring": Surface(5, 4, 4, "xyxY" * 3),
    "macbeath": Surface(7, 3, 7, 8),
    "triplet": Surface(7, 3, 14, 13),
}

#: How many copies of the surface the web app's view holds: its area over the
#: surface's. That is what decides how a closed surface plays -- under one copy
#: and a flag at the view's edge has its twin near the opposite edge, so the
#: whole surface reads at a glance; well over one and every cell is on screen
#: two or three times over; well under and most of the surface is off screen.
#: Must match `COVER_COPIES` in hurwitz.ts.
COVER_COPIES = 0.75


def view_shift(p: int, q: int) -> float:
    """How far the view's centre can ever be from the patch's: the pan carries
    it back onto the central p-gon of {p,q}, so its circumradius,
    acosh(cot(pi/p) cot(pi/q)) -- 0.62 for {7,3}, 0.86 for {8,3} and 0.85 for
    {5,4}. Must match `viewShift`."""
    return math.acosh(1 / (math.tan(math.pi / p) * math.tan(math.pi / q)))


def cover_view(surface: str) -> float:
    """How far round the centre of its view the web app shows ``surface``, in
    hyperbolic distance: the radius v whose disc holds `COVER_COPIES` copies of
    the surface. A disc of radius v has area 2 pi (cosh v - 1) and a genus-g
    surface 4 pi (g - 1), so cosh v = 1 + 2 COVER_COPIES (g - 1): 1.57 on the
    Bolza surface, 2.06 on genus 3 (Klein's quartic and Dyck's surface), 2.39
    on Bring's surface, 2.99 on Macbeath's surface, 3.71 on the triplet. The
    tiling does not enter -- a subdivision makes the tiles smaller, not the
    surface -- so every difficulty of a surface shows the same view, its cells
    smaller the harder it is, as a flat board's are. The pan keeps the view's
    centre on the central tile and hides whatever it would draw farther out,
    which keeps the board's edge one fixed circle as the view steps from tile
    to tile. Must match `coverView`."""
    genus = CLOSED_SURFACES[surface].genus
    return math.acosh(1 + 2 * COVER_COPIES * (genus - 1))


@functools.cache
def _tile_radius(p: int, q: int, op: str) -> float:
    """The farthest any tile's corner is from its own centre, in hyperbolic
    distance, measured on the disc's first rings (the tiles are congruent by
    type, so a few rings hold every kind). Must match `tileRadius`."""
    n = _gc_order(op)
    if n is not None:
        loops, where, centres, _ = gc_loops(p, q, n, 3)
    elif op == "none":
        faces, _, pos, centres = _tiling(p, q, 3)
        loops, where = faces, pos
    else:
        loops, where, centres, _ = wythoff_loops(p, q, op, 3)
    return max(_distance(_to_origin(z, where[k])) for loop, z in zip(loops, centres)
               for k in loop)


def patch_reach(surface: str, op: str) -> float:
    """How far from the centre the patch always reaches: past every face whose
    centre is this close, whatever the surface. The patch has to fill the
    view's circle from anywhere the pan leaves the view's centre, so this is
    `cover_view`, plus `view_shift`, plus the tiling's own tile radius -- a
    tile whose centre is farther out cannot reach into the view. Must match
    `patchReach`."""
    p, q, _, _ = CLOSED_SURFACES[surface]
    return cover_view(surface) + view_shift(p, q) + _tile_radius(p, q, op)

#: The tilings a surface can be drawn in: ``"none"`` is its {p,q} itself, then
#: its Wythoff tilings (`hyperbolic.WYTHOFF_OPS`, bar ``truncate``: 3.14.14's
#: triangles are tiny beside its 14-gons), then its Goldberg--Coxeter
#: subdivisions GC(n, 0), ``"gc2"`` .. ``"gc8"`` (`gc_loops`).
HURWITZ_OPS = ("none", *(op for op in WYTHOFF_OPS if op != "truncate"),
               *(f"gc{n}" for n in range(2, 9)))

#: Each surface's mode: one surface a mode, whatever the difficulty, which
#: grows the board by changing the tiling -- {p,q} itself, a Wythoff tiling of
#: it, or a Goldberg--Coxeter subdivision -- never the surface.
SURFACE_MODES: dict[str, str] = {name: name for name in CLOSED_SURFACES}

Matrix = tuple[int, int, int, int]


def _gc_order(op: str) -> int | None:
    """The n of a Goldberg--Coxeter tiling ``"gc<n>"``, or None for any other."""
    return int(op[2:]) if op.startswith("gc") else None


def _field(q: int):
    """Addition, multiplication and negation in GF(q): integers mod q for a
    prime, three-bit polynomials mod x^3 + x + 1 for 8."""
    if q == 8:
        def mul(a: int, b: int) -> int:
            r = 0
            for i in range(3):
                if b >> i & 1:
                    r ^= a << i
            for i in (4, 3):
                if r >> i & 1:
                    r ^= 0b1011 << (i - 3)
            return r
        return (lambda a, b: a ^ b), mul, (lambda a: a)
    return (lambda a, b: (a + b) % q), (lambda a, b: a * b % q), (lambda a: -a % q)


@functools.cache
def hurwitz_group(q: int) -> tuple[list[Matrix], object, Matrix, Matrix]:
    """PSL(2,q): its elements in order (a matrix (a, b, c, d) named by the
    lesser of it and its negative), its multiplication, and the Hurwitz
    generators x (order 2) and y (order 3), xy of order 7 -- the first such
    pair, x then y in element order, that generates the whole group."""
    add, mul, neg = _field(q)

    def canon(m: Matrix) -> Matrix:
        return min(m, tuple(neg(c) for c in m))

    elements = sorted({
        canon(m) for m in itertools.product(range(q), repeat=4)
        if add(mul(m[0], m[3]), neg(mul(m[1], m[2]))) == 1
    })

    @functools.cache
    def times(m: Matrix, n: Matrix) -> Matrix:
        a, b, c, d = m
        e, f, g, h = n
        return canon((add(mul(a, e), mul(b, g)), add(mul(a, f), mul(b, h)),
                      add(mul(c, e), mul(d, g)), add(mul(c, f), mul(d, h))))

    identity = canon((1, 0, 0, 1))

    def order(m: Matrix) -> int:
        k, power = 1, m
        while power != identity:
            power, k = times(power, m), k + 1
        return k

    def generates(x: Matrix, y: Matrix) -> bool:
        seen, frontier = {identity}, [identity]
        while frontier:
            frontier = [h for g in frontier for h in (times(g, x), times(g, y))
                        if h not in seen and not seen.add(h)]
        return len(seen) == len(elements)

    involutions = [m for m in elements if order(m) == 2]
    triples = [m for m in elements if order(m) == 3]
    for x in involutions:
        for y in triples:
            if order(times(x, y)) == 7 and generates(x, y):
                return elements, times, x, y
    raise ValueError(f"PSL(2,{q}) has no Hurwitz generators")


@functools.cache
def todd_coxeter(p: int, q: int, relator: str, limit: int = 100_000) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """The group <x, y | x^2, y^q, (xy)^p, relator> acting on itself on the
    right: x and y as permutations of its elements, which are numbered in
    breadth-first order from the identity, x before y. That numbering depends
    only on the group and its two generators, so any enumeration -- this one
    is Haselgrove--Leech--Trotter, coset by coset over the trivial subgroup --
    gives the same tables. Raises ValueError if the enumeration outgrows
    ``limit`` cosets (an infinite group, or a presentation it cannot close).
    Must match `toddCoxeter`."""
    # generator columns: x, x^-1, y, y^-1
    inverse = (1, 0, 3, 2)
    letter = {"x": 0, "X": 1, "y": 2, "Y": 3}
    relators = [[0, 0], [2] * q, [0, 2] * p, [letter[c] for c in relator]]
    table: list[list[int | None]] = [[None] * 4]
    parent = [0]

    def find(c: int) -> int:
        while parent[c] != c:
            parent[c] = parent[parent[c]]
            c = parent[c]
        return c

    def coincide(a: int, b: int) -> None:
        pending = [(a, b)]
        while pending:
            a, b = (find(c) for c in pending.pop())
            if a == b:
                continue
            a, b = min(a, b), max(a, b)
            parent[b] = a
            for g in range(4):
                t = table[b][g]
                if t is None:
                    continue
                table[b][g] = None
                if table[t][inverse[g]] == b:
                    table[t][inverse[g]] = None
                u = table[a][g]
                if u is None:
                    table[a][g] = t
                    back = table[t][inverse[g]]
                    if back is None:
                        table[t][inverse[g]] = a
                    else:
                        pending.append((back, a))
                else:
                    pending.append((u, t))
                    if table[t][inverse[g]] is None:
                        table[t][inverse[g]] = find(a)

    def define(c: int, g: int) -> int:
        if len(table) >= limit:
            raise ValueError("the coset enumeration does not close")
        n = len(table)
        table.append([None] * 4)
        parent.append(n)
        table[c][g] = n
        table[n][inverse[g]] = c
        return n

    def scan(c: int, word: list[int]) -> None:
        # trace the relator forward from c, then backward, defining the gap
        f, i = c, 0
        while i < len(word) and table[f][word[i]] is not None:
            f, i = table[f][word[i]], i + 1
        if i == len(word):
            if f != c:
                coincide(f, c)
            return
        b, j = c, len(word) - 1
        while j >= i and table[b][inverse[word[j]]] is not None:
            b, j = table[b][inverse[word[j]]], j - 1
        if j < i:
            coincide(f, b)
            return
        while i < j:
            f, i = define(f, word[i]), i + 1
        table[f][word[i]] = b
        table[b][inverse[word[i]]] = f

    c = 0
    while c < len(table):
        for word in relators:
            if find(c) != c:
                break
            scan(c, word)
        if find(c) == c:
            for g in range(4):
                if table[c][g] is None:
                    define(c, g)
        c += 1
    # renumber the live cosets breadth-first from the identity, x before y
    number = {0: 0}
    order = [0]
    for c in order:
        for g in (0, 2):
            d = find(table[c][g])
            if d not in number:
                number[d] = len(order)
                order.append(d)
    step_x = tuple(number[find(table[c][0])] for c in order)
    step_y = tuple(number[find(table[c][2])] for c in order)
    return step_x, step_y


@functools.cache
def _darts(surface: str) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """How x and y act on the surface's darts, numbered 0 .. |G| - 1: for a
    Hurwitz group the elements of PSL(2,q) in order, times x or y on the right;
    for a presentation the cosets `todd_coxeter` counts."""
    if surface not in CLOSED_SURFACES:
        raise ValueError(f"unknown closed surface {surface!r}")
    p, q, _, group = CLOSED_SURFACES[surface]
    if isinstance(group, str):
        return todd_coxeter(p, q, group)
    elements, times, x, y = hurwitz_group(group)
    index = {g: i for i, g in enumerate(elements)}
    return (tuple(index[times(g, x)] for g in elements),
            tuple(index[times(g, y)] for g in elements))


@functools.cache
def hurwitz_map(surface: str) -> list[tuple[int, ...]]:
    """The surface's {p,q} map: each face as its p vertex ids in order.
    Faces and vertices are numbered in the order of the first dart of their
    coset, so the numbering is the group's own."""
    step_x, step_y = _darts(surface)
    p, q, _, _ = CLOSED_SURFACES[surface]
    turn = [step_y[step_x[d]] for d in range(len(step_x))]

    def cosets(step: list[int] | tuple[int, ...], n: int) -> list[int]:
        out: list[int | None] = [None] * len(step)
        k = 0
        for d in range(len(step)):
            if out[d] is not None:
                continue
            for _ in range(n):
                out[d] = k
                d = step[d]
            k += 1
        return out  # type: ignore[return-value]

    face_of, vertex_of = cosets(turn, p), cosets(step_y, q)
    faces: dict[int, tuple[int, ...]] = {}
    for d in range(len(turn)):
        if face_of[d] in faces:
            continue
        corners, h = [], d
        for _ in range(p):
            corners.append(vertex_of[h])
            h = turn[h]
        faces[face_of[d]] = tuple(corners)
    return [faces[f] for f in range(len(faces))]


def petrie_length(surface: str) -> int:
    """The length of the map's Petrie polygons -- the walk along its edges
    that turns left and right at alternate corners -- which tells the three
    surfaces of the first Hurwitz triplet apart (the quartic's is 8, as its
    classical name {7,3}_8 says)."""
    faces = hurwitz_map(surface)
    p = len(faces[0])
    left: dict[tuple[int, int], int] = {}  # directed edge -> the next corner on its left
    right: dict[tuple[int, int], int] = {}  # ...and on its right
    for face in faces:
        for i in range(p):
            u, v, w = face[i - 1], face[i], face[(i + 1) % p]
            left[(u, v)] = w  # the face runs u -> v -> w counterclockwise
            right[(w, v)] = u  # so arriving at v from w, u is on the right
    start = edge = (faces[0][0], faces[0][1])
    steps = 0
    while True:
        turn = left if steps % 2 == 0 else right
        edge = (edge[1], turn[edge])
        steps += 1
        if edge == start and steps % 2 == 0:
            return steps


@functools.cache
def _cover(surface: str, rings: int) -> tuple[list[int], dict[int, int]]:
    """The covering map from the {p,q} disc out to ``rings`` rings onto the
    surface: each disc face's surface face, and each disc vertex's surface
    vertex. Pure ids -- see the module docstring."""
    p, q, _, _ = CLOSED_SURFACES[surface]
    faces = hurwitz_map(surface)
    across: dict[tuple[int, int], tuple[int, int]] = {}  # directed edge -> (face, corner)
    for f, face in enumerate(faces):
        for i in range(p):
            across[(face[i], face[(i + 1) % p])] = (f, i)
    base = _tiling(p, q, rings)[0]
    disc_face: dict[tuple[int, int], int] = {}
    for f, face in enumerate(base):
        for i in range(p):
            disc_face[(face[i], face[(i + 1) % p])] = f
    vertex: dict[int, int] = dict(zip(base[0], faces[0]))
    face_map = {0: 0}
    stack = [0]
    while stack:
        f = stack.pop()
        face = base[f]
        for i in range(p):
            a, b = face[i], face[(i + 1) % p]
            g = disc_face.get((b, a))
            if g is None or g in face_map:
                continue
            h, k = across[(vertex[b], vertex[a])]
            start = base[g].index(b)
            for s in range(p):
                v, w = base[g][(start + s) % p], faces[h][(k + s) % p]
                if vertex.setdefault(v, w) != w:
                    raise ValueError("the disc does not cover the surface")
            face_map[g] = h
            stack.append(g)
    return [face_map[f] for f in range(len(base))], vertex


# -- the subdivided tilings: Goldberg--Coxeter GC(n, 0) ------------------------
#
# The dual of {p,q} is {q,p}: a q-gon for every corner of the p-gons, its own
# corners the centres of the q faces that meet there. Cut every one of those
# into small ones -- a triangle (q = 3) into n * n small triangles, a square
# (q = 4) into an n x n grid -- and take the dual again, and the p-gons come
# back, one round every p-gon's centre, with hexagons (q = 3) or squares
# (q = 4) everywhere else: GC(n, 0) of {p,q}, q-valent like {p,q}, every
# cell as many neighbours as it has sides.
# On a surface with F faces, V corners and E edges it is
# F + E (n - 1) + V (n - 1)(n - 2) / 2 cells for q = 3 -- 108, 248 and 444 on
# Klein's quartic for n = 2, 3, 4 -- and F + E (n - 1) + V (n - 1)^2 for q = 4.
#
# **The ids are exact.** A point of the cut is named by what it lies inside --
# nothing for a face's centre, the edge it crosses (its two ends, sorted) for a
# point on a side of the dual, the corner of {p,q} for a point inside a dual
# q-gon -- and by its weights over its dual q-gon's corners, the corners being
# faces of the ring walk: the sorted pairs (face, weight) with a weight that is
# not zero, as `solids._geodesic` names the points of an icosahedron's. A
# triangle's point (a, b) weighs (n - a - b, a, b); a square's (i, j) the
# bilinear (n - i)(n - j), i (n - j), i j, (n - i) j. A point on a shared side
# gets the same name from both of its dual polygons, and a point at a corner
# from all p. What it lies inside is what keeps the name one point's on a small
# surface, where two faces can share two edges or three faces meet at two
# corners (the Bolza surface does both). A small polygon is named by its
# points. Nothing is rounded.
#
# **The positions are only drawn.** A point is the weighted average of its
# corners' centres on the hyperboloid, a small polygon the average of its
# points, and the edges between are drawn as geodesic arcs like every other
# disc board's; the floats order a cell's corners round it and nothing else.


def _stars(p: int, q: int, rings: int) -> list[tuple[int, tuple[int, ...], tuple[int, ...]]]:
    """The dual {q,p} of the {p,q} disc out to ``rings`` rings: for every
    vertex with all q of its faces, the vertex, its faces counterclockwise
    from the least, and the far end of the edge each face shares with the
    next. In vertex order, as `hyperbolic._dual_faces` lists {3,q}."""
    faces = _tiling(p, q, rings)[0]
    star: dict[int, list[tuple[int, int, int]]] = {}
    for f, face in enumerate(faces):
        for i, v in enumerate(face):
            star.setdefault(v, []).append((f, face[i - 1], face[(i + 1) % p]))
    out = []
    for v in sorted(star):
        if len(star[v]) < q:
            continue
        # counterclockwise round v, face g is followed by the face whose corner
        # after v is g's corner before v: the two share that edge
        prev = {f: u for f, u, _ in star[v]}
        by_next = {w: f for f, _, w in star[v]}
        order = [min(prev)]
        while len(order) < q:
            order.append(by_next[prev[order[-1]]])
        out.append((v, tuple(order), tuple(prev[f] for f in order)))
    return out


@functools.cache
def gc_loops(p: int, q: int, n: int, rings: int):
    """GC(n, 0) of the {p,q} disc out to ``rings`` rings (q of 3 or 4), in the
    shape `hyperbolic.wythoff_loops` returns: each cell as the loop of its
    corners' keys (the small polygons round a point of the cut,
    counterclockwise), the keys' positions, each cell's centre (its point),
    and what it stands on (the point's key, ``(support, pairs)``). A point is
    kept only where every small polygon round it was built."""
    if n < 2:
        raise ValueError("a subdivision needs n of at least 2")
    if q not in (3, 4):
        raise ValueError("a subdivision needs a tiling of valence 3 or 4")
    _, _, _, centres = _tiling(p, q, rings)
    lifted = [_lift(z) for z in centres]

    def blend(points: list[tuple[float, float, float]], weights: list[float]) -> complex:
        return _drop(tuple(sum(w * p[axis] for p, w in zip(points, weights)) for axis in range(3)))

    point_at: dict[tuple, complex] = {}
    around: dict[tuple, list[tuple]] = {}
    where: dict[tuple, complex] = {}
    order: list[tuple] = []
    for v, corners, shared in _stars(p, q, rings):
        def point(weights: tuple[int, ...]) -> tuple:
            held = [i for i, w in enumerate(weights) if w]
            if len(held) == 1:
                support: tuple = ()
            elif len(held) == 2:
                # corners i and i + 1 (cyclically) share the edge to shared[i]
                i = held[1] if held == [0, q - 1] else held[0]
                support = tuple(sorted((v, shared[i])))
            else:
                support = (v,)
            key = (support, tuple(sorted((corners[i], weights[i]) for i in held)))
            if key not in point_at:
                point_at[key] = blend([lifted[f] for f in corners], list(weights))
                order.append(key)
            return key

        smalls = []
        if q == 3:
            for a in range(n):
                for b in range(n - a):
                    smalls.append((point((n - a - b, a, b)), point((n - a - 1 - b, a + 1, b)),
                                   point((n - a - b - 1, a, b + 1))))
                    if a + b <= n - 2:
                        smalls.append((point((n - a - b - 1, a + 1, b)),
                                       point((n - a - b - 2, a + 1, b + 1)),
                                       point((n - a - b - 1, a, b + 1))))
        else:
            def grid(i: int, j: int) -> tuple:
                return point(((n - i) * (n - j), i * (n - j), i * j, (n - i) * j))

            for i in range(n):
                for j in range(n):
                    smalls.append((grid(i, j), grid(i + 1, j), grid(i + 1, j + 1), grid(i, j + 1)))
        for small in smalls:
            key = tuple(sorted(small))
            if key in where:
                continue
            where[key] = blend([_lift(point_at[k]) for k in small], [1.0] * len(small))
            for k in small:
                around.setdefault(k, []).append(key)
    loops, cell_centres, origins = [], [], []
    for key in order:
        smalls = around[key]
        if len(smalls) != (p if len(key[1]) == 1 else 2 * q if q == 3 else q):
            continue  # a small polygon round it was not built
        z = point_at[key]
        smalls = sorted(smalls, key=lambda t: cmath.phase(_to_origin(z, where[t])))
        loops.append(tuple(smalls))
        cell_centres.append(z)
        origins.append(key)
    return loops, where, cell_centres, origins


def _patch(surface: str, op: str, rings: int):
    """The disc out to ``rings`` rings in tiling ``op``, and how it covers the
    surface: each face's loop of keys, the keys' positions, the face centres,
    each face's surface cell, and a function sending a key to its surface
    vertex."""
    p, q, _, _ = CLOSED_SURFACES[surface]
    phi_face, phi = _cover(surface, rings)
    if op == "none":
        base, _, pos, centres = _tiling(p, q, rings)
        cells = [("F", phi_face[f]) for f in range(len(base))]
        return [tuple(face) for face in base], pos, centres, cells, phi.__getitem__
    n = _gc_order(op)
    if n is not None:
        loops, where, centres, origins = gc_loops(p, q, n, rings)

        def down(point: tuple) -> tuple:
            support, pairs = point
            return (tuple(sorted(phi[v] for v in support)),
                    tuple(sorted((phi_face[f], w) for f, w in pairs)))

        return (loops, where, centres, [("G", down(o)) for o in origins],
                lambda k: tuple(sorted(down(pt) for pt in k)))
    loops, where, centres, origins = wythoff_loops(p, q, op, rings)

    def cell(origin: tuple) -> tuple:
        if origin[0] == "F":
            return ("F", phi_face[origin[1]])
        if origin[0] == "V":
            return ("V", phi[origin[1]])
        return ("E", *sorted((phi[origin[1]], phi[origin[2]])))

    def key(k: tuple) -> tuple:
        if op == "ambo":
            return tuple(sorted((phi[k[0]], phi[k[1]])))
        if op == "zip":
            return (phi_face[k[0]], *sorted((phi[k[1]], phi[k[2]])))
        if op == "expand":
            return (phi_face[k[0]], phi[k[1]])
        return (phi_face[k[0]], phi[k[1]], phi[k[2]])

    return loops, where, centres, [cell(o) for o in origins], key


def _patch_for(surface: str, op: str, margin: int):
    """Grow the disc until it holds every face out to the shells the patch
    keeps -- the first shells to reach every cell or out to `patch_reach`,
    whichever is farther, and ``margin`` more -- with a unit to spare past the
    last, as `hyperbolic._rings_for` grows it. Returns the patch and its
    shells."""
    p, q, _, _ = CLOSED_SURFACES[surface]
    target = len(hurwitz_cells(surface, op))
    for rings in range(2, 13):
        loops, where, centres, cells, key = _patch(surface, op, rings)
        groups = _shell_groups(centres)
        seen: set = set()
        cover = None
        for s, group in enumerate(groups):
            seen.update(cells[f] for f in group)
            if len(seen) == target:
                cover = s + 1
                break
        if cover is None:
            continue
        far = patch_reach(surface, op)
        reach = sum(1 for group in groups if _distance(centres[group[0]]) <= far)
        keep = max(cover, reach) + margin
        if len(groups) <= keep:
            continue
        _, ring_of, _, base_centres = _tiling(p, q, rings)
        outer = min(_distance(z) for z, r in zip(base_centres, ring_of) if r == rings)
        cut = _distance(centres[groups[keep - 1][0]])
        if outer > cut + 1.0 and outer > far + 1.0:
            return (loops, where, centres, cells, key), groups[:keep]
    raise ValueError("the patch needs too many rings")


def cell_count(surface: str, op: str) -> int:
    """How many cells the surface has in tiling ``op``: F, V and E are its
    map's, so this is arithmetic, not a build."""
    p, q, genus, _ = CLOSED_SURFACES[surface]
    # chi = V - E + F with pF = 2E = qV
    faces = (2 - 2 * genus) * 2 * q // (2 * q - p * q + 2 * p)
    edges, vertices = p * faces // 2, p * faces // q
    n = _gc_order(op)
    if n is not None:
        if q == 3:
            return faces + edges * (n - 1) + vertices * (n - 1) * (n - 2) // 2
        return faces + edges * (n - 1) + vertices * (n - 1) ** 2
    return faces + {"none": 0, "zip": vertices, "ambo": vertices,
                    "expand": vertices + edges, "bevel": vertices + edges}[op]


@functools.cache
def hurwitz_cells(surface: str, op: str) -> dict[tuple, list]:
    """The surface's cells in tiling ``op``, each as its corners' surface
    vertex ids in order, keyed by what it stands on (``("F", face)``,
    ``("V", vertex)``, ``("E", u, v)``, or a subdivision's point
    ``("G", (support, ((face, weight), ...)))``). Read off a disc big enough
    to hold a copy of every one of them."""
    if op not in HURWITZ_OPS:
        raise ValueError(f"unknown tiling {op!r}")
    if surface not in CLOSED_SURFACES:
        raise ValueError(f"unknown closed surface {surface!r}")
    if _gc_order(op) is not None and CLOSED_SURFACES[surface].q not in (3, 4):
        raise ValueError(f"{surface} has no subdivision")
    want = cell_count(surface, op)
    for rings in range(2, 13):
        loops, _, _, cells, key = _patch(surface, op, rings)
        out: dict[tuple, list] = {}
        for loop, cell in zip(loops, cells):
            corners = [key(k) for k in loop]
            if cell in out:
                if not _same_loop(out[cell], corners):
                    raise ValueError("two copies of a cell disagree")
            else:
                out[cell] = corners
        if len(out) == want:
            return out
        if len(out) > want:
            raise ValueError("the surface has more cells than its map counts")
    raise ValueError("the disc never reaches every cell")


def _same_loop(a: list, b: list) -> bool:
    """Whether two loops are the same cycle, read from any start."""
    if len(a) != len(b) or a[0] not in b:
        return False
    i = b.index(a[0])
    return a == b[i:] + b[:i]


def hurwitz_board(
    surface: str,
    op: str,
    margin: int,
    mine_count: int,
    scale: float = 300.0,
    arc: int = ARC_SEGMENTS,
) -> Board:
    """The closed surface ``surface`` (one of `CLOSED_SURFACES`) in tiling ``op``
    (one of `HURWITZ_OPS`; the boards that ship are ``none``, ``zip``,
    ``expand`` (Bring's surface's 4.4.4.5) and ``gc2`` .. ``gc8``), drawn as a patch of the Poincaré disc
    that covers it: the shells out to where every cell has a copy, and
    ``margin`` more. The board is the surface's mode (`SURFACE_MODES`).
    ``scale`` and ``arc`` are `hyperbolic.hyperbolic_board`'s."""
    if margin < 0:
        raise ValueError("margin must not be negative")
    surface_cells = hurwitz_cells(surface, op)
    (loops, where, _, cells, key), groups = _patch_for(surface, op, margin)
    drawn = [f for group in groups for f in sorted(group)]
    ids: dict = {}
    faces: list[tuple[int, ...]] = []
    for f in drawn:
        faces.append(tuple(ids.setdefault(k, len(ids)) for k in loops[f]))
    pos = {i: where[k] for k, i in ids.items()}
    _, mask, polygons, size = disc_drawing(faces, list(range(len(faces))), pos, scale, arc)
    # each cell is named after its copy nearest the centre: the first drawn
    name: dict[tuple, int] = {}
    for face, f in enumerate(drawn):
        name.setdefault(cells[f], face)
    face_cell = {face: name[cells[f]] for face, f in enumerate(drawn)}
    quotient = {name[cell]: corners for cell, corners in surface_cells.items()}
    return Board(
        SURFACE_MODES[surface],
        polygons,
        _shared_vertex_adjacency(quotient),
        mine_count,
        size,
        size,
        corner_mask=mask,
        faces=face_cell,
        quotient=quotient,
    )
