"""The closed hyperbolic surfaces: a regular {p,q} tiling glued up into a
surface with no edge at all, drawn as a patch of the Poincaré disc that covers
it.

A disc of the hyperbolic plane is mostly rim -- its boundary grows as fast as
its area -- and a rim cell sees far fewer than its tile's neighbours. Glue the
plane up into a closed surface and the rim is gone: every cell keeps its full
count, as on a sphere. Every surface here is one on which its tiling closes up
regularly -- every face looks like every other. Most are the **Hurwitz
surfaces**, the ones with the most symmetry their genus allows (84(g - 1)
turns), the {7,3} tiling's (the module is named after them):

* ``quartic``, Klein's quartic: genus 3, 24 heptagons, the group PSL(2,7);
* ``macbeath``, Macbeath's surface: genus 7, 72 heptagons, PSL(2,8);
* ``triplet``, one of the first Hurwitz triplet: genus 14, 156 heptagons,
  PSL(2,13). The three surfaces of the triplet share the group and are not
  the same surface; this is the one the generator search below meets first,
  and `TestHurwitz` pins which by its Petrie polygons.

and three are the most symmetric surfaces of their genus for another tiling:

* ``bolza``, the Bolza surface: genus 2, 6 octagons of {8,3}, 48 turns;
* ``dyck``, Dyck's surface: genus 3, 12 octagons of {8,3}, 96 turns;
* ``bring``, Bring's surface: genus 4, 24 pentagons of {5,4}, 120 turns (the
  group S5).

The count of heptagons is fixed by the surface -- a genus-g Hurwitz surface
has 84(g - 1) turns, seven to a face, so 12(g - 1) of them -- and so is the
size of its 6.6.7 (the {7,3} tiling's ``zip``, a hexagon on every corner): 80,
240 and 520 cells. Each surface is a mode of its own (`SURFACE_MODES`), and
grows from difficulty to difficulty by changing its tiling, never the surface:
{7,3} itself, its 6.6.7, or a Goldberg--Coxeter subdivision GC(n, 0)
(`gc_loops`). Klein's quartic goes 80, 248, 444; Macbeath's surface 72, 240,
324; the triplet 156, 520, 702. The other three count the same way from their
own faces: the Bolza surface goes 70, 286, 510 (GC(3,0), GC(6,0), GC(8,0)),
Dyck's surface 60, 252, 396 (GC(2,0), GC(4,0), GC(5,0)), and Bring's surface
114, 264, 474 (4.4.4.5, then the square subdivision of a 4-valent tiling,
GC(3,0) and GC(4,0)).

**The surface is built from its group, exactly.** The group of a regular
{p,q} map is generated by an x of order 2 and a y of order q whose product
R = xy has order p, and the map is read straight off it: the group's elements
are the map's darts, the cosets of <R> its faces, of <y> its vertices and of
<x> its edges, and a face's corners run in <R> order. Only how x and y act on
the darts is needed (`_darts`), and it comes one of two ways, both all
integers, so nothing is ever rounded:

* a Hurwitz group is PSL(2,q) -- 2x2 matrices of determinant 1 over the field
  of q elements, a matrix and its negative counted once. GF(7) and GF(13) are
  integers mod p; GF(8) is three bits, multiplied as polynomials mod
  x^3 + x + 1. The generators are the first pair met in a fixed order;
* any other surface is a presentation, <x, y | x^2, y^q, (xy)^p, w>, its
  darts the cosets a Todd--Coxeter enumeration counts (`todd_coxeter`),
  renumbered in breadth-first order from the identity so the numbering is the
  group's and not the enumeration's.

**The disc covers the surface, and the covering map is combinatorial.** The
{p,q} tiling the ring walk builds (`hyperbolic.py`) is the surface's universal
cover. The central p-gon's corners go in order onto face 0's; then every
disc face across an edge from one already mapped goes onto the one surface face
across that edge's image, which the surface has exactly one of. That is a
breadth-first walk on ids alone; a disc vertex reached two ways must land on
one surface vertex, which the walk checks. A uniform tiling of the disc
(`hyperbolic.wythoff_loops`) is carried down through its flag keys.

**The patch is the shells out to where every cell has been drawn once** -- and
at least out to `patch_reach`, so the web app's pan always has board round the
view -- plus ``margin`` more, so every cell is somewhere on the board and the
drawing keeps the central p-gon's p turns and mirrors. Each drawn face shows the cell
it covers (``Board.faces``); the cell is named after its copy nearest the
centre. Adjacency is the *surface's*, from the cells' corners as surface ids
(``Board.quotient``) -- so a cell is a full neighbour of its neighbours even
where its copy sits at the rim of the patch, and the topology helpers count
the surface, chi = 2 - 2g, rather than the disc.
"""

